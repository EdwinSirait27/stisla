@push('scripts')
    <script src="https://cdn.datatables.net/1.13.6/js/jquery.dataTables.min.js"></script>
    <script src="https://cdn.jsdelivr.net/npm/select2@4.1.0-rc.0/dist/js/select2.min.js"></script>
    <script src="https://cdn.jsdelivr.net/npm/sweetalert2@11"></script>
    @include('partials.datatables-error', ['permission' => 'ManageFingerspotRecap'])
    <script>
        $(function() {
            const esc = v => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
            const DEF = { start: @json($defaultStart), end: @json($defaultEnd), period: $('#period').val() };
            const canRecap = @json(auth()->user()->can('ManageFingerspot'));
            $('.js-s2').each(function() { $(this).select2({ width: '100%' }); });

            function syncCustom() {
                const v = $('#period').val();
                $('[data-custom]').prop('hidden', v !== 'custom');
                if (v && v !== 'custom') { const [a, b] = v.split('|'); $('#startDate').val(a); $('#endDate').val(b); }
            }
            syncCustom();

            // Catatan dari arsip: "dd/mm/yyyy" = telat atau tidak masuk, "dd/mm/yyyy (keterangan)" = PH, cuti, sakit, TOIL
            function parseRemarks(r) {
                if (!r || r === '-') return [];
                const out = [], re = /(\d{2}\/\d{2}\/\d{4})(?:\s*\(([^)]*)\))?/g; let m;
                while ((m = re.exec(r))) out.push({ date: m[1], label: m[2] || null });
                return out;
            }
            function notesCell(r) {
                const items = parseRemarks(r);
                if (!items.length) return '<span class="pr-muted">-</span>';
                const bad = items.filter(i => !i.label).length;
                const groups = {};
                items.filter(i => i.label).forEach(i => {
                    const k = /leave|cuti/i.test(i.label) ? 'Cuti' : /sick|sakit/i.test(i.label) ? 'Sakit' : /toil/i.test(i.label) ? 'TOIL' : 'Libur nasional';
                    groups[k] = (groups[k] || 0) + 1;
                });
                const chips = (bad ? `<span class="fr-chip is-bad">${bad} telat / tidak masuk</span>` : '')
                    + Object.entries(groups).map(([k, n]) => `<span class="fr-chip is-ok">${n} ${esc(k)}</span>`).join('');
                const list = items.map(i => `<li class="${i.label ? '' : 'is-bad'}"><b>${esc(i.date)}</b><span>${esc(i.label || 'telat atau tidak masuk')}</span></li>`).join('');
                return `<details class="fr-notes"><summary><span class="fr-chips">${chips}</span><span class="lv-link">${items.length} tanggal</span></summary><ul class="fr-list">${list}</ul></details>`;
            }

            const table = $('#recap-table').DataTable({
                processing: true, serverSide: true, autoWidth: false,
                dom: 'rt<"pr-dt-bottom"<"pr-dt-left"li>p>',
                pageLength: 25, lengthMenu: [[10, 25, 50, 100, -1], [10, 25, 50, 100, 'Semua']],
                order: [[0, 'asc']],
                language: {
                    processing: 'Memuat', lengthMenu: 'Tampilkan _MENU_', info: '_START_ sampai _END_ dari _TOTAL_', infoEmpty: 'Tidak ada data',
                    infoFiltered: '', zeroRecords: 'Tidak ada karyawan yang cocok.', emptyTable: 'Tidak ada karyawan untuk filter ini.',
                    paginate: { previous: 'Sebelumnya', next: 'Berikutnya' },
                },
                ajax: {
                    url: '{{ route('fingerprint-recap.data') }}', type: 'POST', headers: { 'X-CSRF-TOKEN': '{{ csrf_token() }}' },
                    data: d => { d.start_date = $('#startDate').val(); d.end_date = $('#endDate').val(); d.store_name = $('#store_name').val(); d.status_name = $('#status_name').val(); },
                },
                columns: [
                    { data: 'employee_name', render: (d, t, r) => t !== 'display' ? d
                        : `<span class="pr-cell-name">${esc(d)}</span><span class="pr-cell-sub">${esc([r.employee_pengenal !== '-' ? r.employee_pengenal : null, r.status_employee !== '-' ? r.status_employee : null, r.status_name !== 'Active' ? r.status_name : null].filter(Boolean).join(', '))}</span>` },
                    { data: 'store_name', render: d => esc(d) },
                    { data: 'total_hari_num', className: 'text-right', render: (d, t, r) => t !== 'display' ? d
                        : (r.has_archive ? `<span class="fr-days ${d === 0 ? 'is-none' : ''}">${d} <small>hari</small></span>` : '<span class="pr-cell-sub">belum direkap</span>') },
                    { data: 'total_telat_num', className: 'text-right', render: (d, t, r) => t !== 'display' ? d
                        : (r.has_archive ? `<span class="fr-days ${d > 0 ? 'is-late' : 'is-none'}">${d} <small>hari</small></span>` : '<span class="pr-muted">-</span>') },
                    { data: 'remarks', orderable: false, render: (d, t) => t !== 'display' ? d : notesCell(d) },
                ],
                drawCallback: function(settings) {
                    const json = settings.json; if (!json || !json.stats) return;
                    const s = json.stats, n = v => Number(v || 0).toLocaleString('id-ID');
                    $('#rc-count').text(`${n(json.recordsFiltered)} karyawan, ${s.period}`);
                    $('#st-emp').text(n(s.employees)); $('#st-emp-sub').text(`${n(s.archived)} sudah direkap`);
                    $('#st-avg').text(String(s.avg_days).replace('.', ','));
                    $('#st-late').text(n(s.late_people)); $('#st-late-sub').text(`${n(s.late_days)} hari telat totalnya`);
                    $('#st-zero').text(n(s.zero_days)); $('#st-miss').text(n(s.missing));
                    $('#late-box').toggleClass('is-warn', s.late_people > 0); $('#zero-box').toggleClass('is-warn', s.zero_days > 0);
                    $('#miss-box').toggleClass('is-warn', s.missing > 0 && s.archived > 0);
                    const $b = $('#period-banner').removeClass('is-warn is-muted');
                    if (!s.archived) {
                        $b.addClass('is-warn').html(`<span><strong>Periode ${esc(s.period)} belum direkap.</strong> Semua angka di bawah 0 karena belum ada arsip, bukan karena karyawan tidak hadir. ${canRecap ? 'Jalankan Rekap absensi di halaman Absensi fingerprint dengan tanggal yang sama persis.' : 'Minta HR menjalankan Rekap absensi untuk periode ini.'}</span>`
                            + (canRecap ? `<a class="pr-btn pr-btn-sm" href="{{ route('pages.Fingerprints') }}">Buka Absensi fingerprint</a>` : ''));
                    } else {
                        $b.html(`<span><strong>Sudah direkap.</strong> Terakhir ${esc(s.last_at)}${s.by ? ' oleh ' + esc(s.by) : ''}. ${s.missing ? n(s.missing) + ' karyawan belum ada di arsip, kemungkinan baru masuk atau belum punya PIN saat rekap dijalankan.' : 'Semua karyawan di filter ini sudah ada di arsip.'}</span>`);
                    }
                },
            });

            let st; $('#rc-search').on('input', function() { clearTimeout(st); const v = this.value; st = setTimeout(() => table.search(v).draw(), 400); });
            $('#period').on('change', () => { syncCustom(); if ($('#period').val() !== 'custom') table.ajax.reload(); });
            $('#store_name, #status_name').on('change', () => table.ajax.reload());
            $('#filterBtn').on('click', () => {
                if ($('#endDate').val() < $('#startDate').val()) return Swal.fire({ icon: 'error', title: 'Tanggal belum benar', text: 'Tanggal selesai tidak boleh sebelum tanggal mulai.' });
                table.ajax.reload();
            });
            $('#resetBtn').on('click', () => {
                $('#period').val(DEF.period); $('#startDate').val(DEF.start); $('#endDate').val(DEF.end); syncCustom();
                $('#store_name').val('').trigger('change.select2'); $('#status_name').val(''); $('#rc-search').val(''); table.search('').ajax.reload();
            });
            $('#exportBtn').on('click', () => {
                const p = new URLSearchParams({ start_date: $('#startDate').val(), end_date: $('#endDate').val(), store_name: $('#store_name').val() || '', status_name: $('#status_name').val() || '' });
                window.location.href = '{{ route('fingerprint-recap.export') }}?' + p;
            });
        });
    </script>
@endpush
