    <script src="https://cdn.datatables.net/1.13.6/js/jquery.dataTables.min.js"></script>
    <script src="https://cdn.jsdelivr.net/npm/sweetalert2@11"></script>
    <script src="https://cdn.jsdelivr.net/npm/select2@4.1.0-rc.0/dist/js/select2.min.js"></script>
    @include('partials.datatables-error', ['permission' => 'assignment'])
    @include('pages.Toil._helpers')
    <script>
        $(function() {
            const T = window.TOIL, HPD = 8;
            let available = 0;
            $.ajaxSetup({ headers: { 'X-CSRF-TOKEN': $('meta[name="csrf-token"]').attr('content') } });
            $('#employee_id').select2({ placeholder: 'Pilih karyawan', allowClear: true, width: '100%' });
            const today = T.todayLocal();
            $('#start_date, #end_date').attr('min', today);

            const countDays = (a, b) => { if (!a || !b) return 0; const d = Math.round((new Date(b) - new Date(a)) / 864e5); return d < 0 ? 0 : d + 1; };
            function refreshTotal() {
                const days = countDays($('#start_date').val(), $('#end_date').val());
                const $b = $('#total-box').removeClass('is-ok is-bad');
                if (!$('#employee_id').val() || !days) { $('#total-display').text('Pilih karyawan dan tanggal dulu'); $('#btn-submit').prop('disabled', true); return; }
                const need = days * HPD;
                $('#btn-submit').prop('disabled', false);
                if (need > available) {
                    $b.addClass('is-bad');
                    $('#total-display').html(`Paling banyak <strong>${days} hari = ${need} jam</strong>, saldo ${T.hours(available)} jam. Bisa tetap cukup kalau ada hari libur di rentang ini, server yang memastikan.`);
                } else {
                    $b.addClass('is-ok');
                    $('#total-display').html(`<strong>${days} hari = ${need} jam</strong>, sisa saldo sekitar ${T.hours(available - need)} jam`);
                }
            }
            function resetForm() {
                $('#formCreateLeave')[0].reset();
                $('#employee_id').val(null).trigger('change.select2');
                $('#saldo-display').text('Pilih karyawan dulu'); $('#saldo-box').removeClass('is-ok is-bad');
                $('#saldo-info').text('Saldo yang paling cepat hangus dipakai lebih dulu.');
                available = 0; refreshTotal();
            }
            $('#start_date').on('change', function() {
                $('#end_date').attr('min', this.value || today);
                if (this.value && (!$('#end_date').val() || $('#end_date').val() < this.value)) $('#end_date').val(this.value);
                refreshTotal();
            });
            $('#end_date').on('change', refreshTotal);
            $('#btn-form-reset').on('click', e => { e.preventDefault(); resetForm(); });

            $('#employee_id').on('change', function() {
                const id = this.value, $box = $('#saldo-box').removeClass('is-ok is-bad');
                available = 0;
                if (!id) { $('#saldo-display').text('Pilih karyawan dulu'); refreshTotal(); return; }
                $('#saldo-display').text('Memuat saldo');
                $.get('{{ url('toil/approval/saldo') }}/' + encodeURIComponent(id))
                    .done(res => {
                        available = parseFloat(String(res.total_remaining || 0).replace(/,/g, ''));
                        if (available <= 0) {
                            $box.addClass('is-bad'); $('#saldo-display').text('Tidak ada saldo TOIL yang bisa dipakai');
                            $('#saldo-info').text('Karyawan ini belum punya lembur TOIL, atau saldonya sudah habis atau hangus.');
                        } else {
                            $box.addClass('is-ok');
                            $('#saldo-display').html(`<strong>${T.hours(available)} jam</strong>&nbsp;(${Math.floor(available / HPD)} hari) dari ${res.count} lembur`);
                            $('#saldo-info').text(res.nearest_expiry ? `Yang paling cepat hangus: ${res.nearest_expiry}. Dipakai lebih dulu.` : 'Saldo yang paling cepat hangus dipakai lebih dulu.');
                        }
                        refreshTotal();
                    })
                    .fail(xhr => { $box.addClass('is-bad'); $('#saldo-display').text(T.errMsg(xhr, 'Gagal memuat saldo')); refreshTotal(); });
            });

            const table = $('#approval-table').DataTable({
                processing: true, autoWidth: false,
                dom: 'rt<"pr-dt-bottom"<"pr-dt-left"li>p>',
                ajax: {
                    url: '{{ route('toil.approval.data') }}',
                    data: d => { d.status = $('#filter-status').val(); d.start_date = $('#filter-start-date').val(); d.end_date = $('#filter-end-date').val(); d.employee_search = $('#filter-employee').val(); },
                    dataSrc: json => { $('#hist-count').text(`${json.data.length} jadwal`); return json.data; }
                },
                order: [[1, 'desc']], pageLength: 25, lengthMenu: [[10, 25, 50, -1], [10, 25, 50, 'Semua']],
                language: T.lang('Belum ada libur TOIL yang dijadwalkan.'),
                columns: [
                    { data: 'employee_name', render: (d, t, r) => t === 'display' ? `<span class="pr-cell-name">${T.esc(d)}</span><span class="pr-cell-sub">${T.esc(r.employee_pengenal || ('PIN ' + r.employee_pin))}</span>` : d },
                    { data: 'start_raw', render: (d, t, r) => t === 'display' ? `<span class="pr-cell-name">${T.esc(String(r.leave_date).replace('→', 'sampai'))}</span><span class="pr-cell-sub">${r.total_days} hari kerja</span>` : d },
                    { data: 'hours_used', className: 'text-right', render: d => `<span class="tl-num">${T.hours(String(d).replace(/,/g, ''))} jam</span>` },
                    { data: 'reason', orderable: false, render: (d, t, r) => `<span class="tl-reason">${T.esc(d || '-')}</span>` + (r.status === 'Cancelled' && r.rejected_reason ? `<span class="pr-cell-sub">Dibatalkan: ${T.esc(r.rejected_reason)}</span>` : '') },
                    { data: 'status', render: d => T.badge(T.OT, d) },
                    { data: 'created_at', render: d => `<span class="pr-cell-sub">${T.esc(d)}</span>` },
                    { data: 'id', orderable: false, className: 'text-right', render: (d, t, r) => r.can_cancel ? `<button type="button" class="pr-btn pr-btn-sm pr-btn-danger btn-cancel" data-id="${T.esc(d)}">Batalkan</button>` : '<span class="pr-muted">-</span>' },
                ],
            });
            $('#btn-filter').on('click', () => table.ajax.reload());
            $('#filter-status').on('change', () => table.ajax.reload());
            let ts; $('#filter-employee').on('input', () => { clearTimeout(ts); ts = setTimeout(() => table.ajax.reload(), 400); });
            $('#btn-reset').on('click', () => { $('#filter-status, #filter-start-date, #filter-end-date, #filter-employee').val(''); table.ajax.reload(); });
            $('#formCreateLeave').on('keydown', e => { if (e.key === 'Enter' && e.target.tagName !== 'TEXTAREA') e.preventDefault(); });

            $('#formCreateLeave').on('submit', function(e) {
                e.preventDefault();
                const s = $('#start_date').val(), en = $('#end_date').val(), days = countDays(s, en);
                if (!days) return Swal.fire({ icon: 'error', title: 'Tanggal belum benar', text: 'Tanggal selesai tidak boleh sebelum tanggal mulai.' });
                if (($('#reason').val() || '').trim().length < 10) return Swal.fire({ icon: 'error', title: 'Alasan terlalu pendek', text: 'Tulis alasan minimal 10 karakter.' });
                const name = $('#employee_id option:selected').text();
                Swal.fire({
                    icon: 'question', title: 'Simpan libur TOIL?',
                    html: `${T.esc(name)}, <strong>${days} hari (${days * HPD} jam)</strong>. Langsung disetujui, saldo dipotong, roster jadi TOIL Off.`,
                    showCancelButton: true, confirmButtonText: 'Simpan', cancelButtonText: 'Batal', confirmButtonColor: '#4f46e5',
                }).then(r => {
                    if (!r.isConfirmed) return;
                    const $btn = $('#btn-submit').prop('disabled', true);
                    $.post('{{ route('toil.approval.store') }}', { employee_id: $('#employee_id').val(), start_date: s, end_date: en, reason: $('#reason').val() })
                        .done(res => { Swal.fire({ icon: 'success', title: 'Tersimpan', text: res.message }); resetForm(); table.ajax.reload(); })
                        .fail(xhr => Swal.fire({ icon: 'error', title: 'Tidak bisa disimpan', text: T.errMsg(xhr, 'Terjadi kesalahan.') }))
                        .always(() => { $btn.prop('disabled', false); refreshTotal(); });
                });
            });

            $('#approval-table').on('click', '.btn-cancel', function() {
                $('#cancel_id').val(this.dataset.id); $('#cancel_reason').val(''); $('#modalCancel').modal('show');
            });
            $('#formCancel').on('submit', function(e) {
                e.preventDefault();
                const reason = $('#cancel_reason').val().trim();
                if (reason.length < 10) return Swal.fire({ icon: 'error', title: 'Alasan terlalu pendek', text: 'Tulis alasan minimal 10 karakter.' });
                const $b = $('#btn-confirm-cancel').prop('disabled', true);
                $.ajax({ url: '{{ url('toil/approval') }}/' + encodeURIComponent($('#cancel_id').val()) + '/cancel', method: 'POST', data: { _method: 'PUT', cancel_reason: reason } })
                    .done(res => { $('#modalCancel').modal('hide'); Swal.fire({ icon: 'success', title: 'Dibatalkan', text: res.message }); table.ajax.reload(); })
                    .fail(xhr => Swal.fire({ icon: 'error', title: 'Gagal membatalkan', text: T.errMsg(xhr, 'Terjadi kesalahan.') }))
                    .always(() => $b.prop('disabled', false));
            });
        });
    </script>
